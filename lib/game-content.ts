export function isGameKind(value: string): value is GameKind {
  return (GAME_KINDS as readonly string[]).includes(value);
}

export function randomGameQuestion(kind: GameKind, previous?: string) {
  const pool = GAME_QUESTIONS[kind];
  const fresh = pool.filter((question) => question.question !== previous);
  const available = fresh.length > 0 ? fresh : pool;
  return available[Math.floor(Math.random() * available.length)];
}

export function correctGameAnswer(question: string) {
  return (
    GAME_QUESTIONS.quiz.find((item) => item.question === question)
      ?.correctAnswer || null
  );
}
